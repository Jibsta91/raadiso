#!/usr/bin/env node
// Writes src/i18n/taxonomy.ts from the website's message catalogues (apps/web/messages, `taxonomy`), so
// the app and the website name every country's categories, subcategories, attributes and values the
// same way (ADR-0040). Run by `pnpm generate` (./raadi generate); api-check fails when it is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '../../web/messages');
const out = join(here, '../src/i18n/taxonomy.ts');
const LOCALES = ['en', 'nb', 'so'];

const parts = LOCALES.map((locale) => {
  const { taxonomy } = JSON.parse(readFileSync(join(web, `${locale}.json`), 'utf8'));
  const { categories, subcategories, attributes, values } = taxonomy;
  return `const ${locale} = ${JSON.stringify({ categories, subcategories, attributes, values }, null, 2)};\n`;
});

writeFileSync(
  out,
  `// Generated by scripts/sync-taxonomy.mjs from apps/web/messages (\`taxonomy\`): do not edit.
// Category, subcategory, attribute and value names for every country, the same words as the website.
// Keys match @raadi/catalog.

${parts.join('\n')}
export const taxonomyMessages = { ${LOCALES.join(', ')} };
`,
);
process.stdout.write(`wrote ${out}\n`);
